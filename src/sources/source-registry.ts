export function getActiveSources(): SourceDescriptor[] {
  return SOURCE_REGISTRY.filter(s => s.implementationStatus === 'active')
}

export function getPlannedSources(): SourceDescriptor[] {
  return SOURCE_REGISTRY.filter(s => s.implementationStatus === 'planned')
}

export function getSourcesForAgent(agentId: string): SourceDescriptor[] {
  return SOURCE_REGISTRY.filter(s => s.agents.includes(agentId))
}

export function getSourceById(id: string): SourceDescriptor | undefined {
  return SOURCE_REGISTRY.find(s => s.id === id)
}
